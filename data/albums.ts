export function getAlbum(slug: string) {
  return albums.find((album) => album.slug === slug)
}

export const albumsByYear = albums.reduce<Record<number, Album[]>>((groups, album) => {
  groups[album.year] ??= []
  groups[album.year].push(album)
  return groups
}, {})
